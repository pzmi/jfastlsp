#!/usr/bin/env bash
# Self-test of scripts/clippy-lists.sh (FND-02) over a small policy fixture: grant sections lifted,
# `#pure` entries only in pure crates (with allow-invalid on their std entries), no file for a
# crate without a grant (a stale one removed), and --check failing on drift. Until FND-07's
# ARCH-clippy-lists lands, this is the generator's only independent check. Needs only bash and awk.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
fail() { echo "FAIL: $*" >&2; exit 1; }

repo="$tmp/repo"
mkdir -p "$repo/scripts" "$repo/crates/granted" "$repo/crates/plain" "$repo/crates/pure"
cp "$here/clippy-lists.sh" "$repo/scripts/"
cat >"$repo/Cargo.toml" <<'TOML'
[workspace]
members = [
    "crates/granted",
    "crates/plain",
    "crates/pure",
]
TOML
cat >"$repo/architecture.toml" <<'TOML'
[roles]
pure = ["pure"]

[grants]
fs = ["granted"]
sleep = ["granted"]
TOML
cat >"$repo/clippy.toml" <<'TOML'
# root header comment, kept out of the generated files

allow-unwrap-in-tests = true

disallowed-methods = [
  # grant: fs
  { path = "std::fs::read", reason = "fs" },
  # grant: sleep
  { path = "std::thread::sleep", reason = "sleep" },
  # grant: env
  { path = "std::env::var", reason = "env" },
  # grant: none
  { path = "tokio::sync::mpsc::unbounded_channel", reason = "none", allow-invalid = true },
]

disallowed-types = [
  # grant: none
  { path = "std::net::TcpStream", reason = "tcp" },
  #pure { path = "core::cell::Cell", reason = "pure" },
]
TOML
echo "stale" >"$repo/crates/plain/clippy.toml"
gen() { bash "$repo/scripts/clippy-lists.sh" "$@"; }

# given the fixture, when the lists are written, then each crate gets what its grants say
gen
granted="$(cat "$repo/crates/granted/clippy.toml")"
pure="$(cat "$repo/crates/pure/clippy.toml")"
grep -q '^# Generated by .just clippy-lists.' <<<"$granted" || fail "no generated header"
if grep -q 'root header comment' <<<"$granted"; then fail "root header copied"; fi
if grep -q 'std::fs::read\|std::thread::sleep' <<<"$granted"; then fail "granted entries kept"; fi
grep -q '# grant: fs (granted to this crate: lifted)' <<<"$granted" || fail "lifted section unmarked"
grep -q '{ path = "std::env::var", reason = "env" },' <<<"$granted" || fail "ungranted entry dropped"
grep -q '{ path = "std::net::TcpStream", reason = "tcp" },' <<<"$granted" || fail "no-grant entry dropped"
if grep -q 'core::cell::Cell' <<<"$granted"; then fail "pure entry in a non-pure crate"; fi
grep -q '^  { path = "core::cell::Cell", reason = "pure" },' <<<"$pure" || fail "pure entry not uncommented"
grep -q '{ path = "std::fs::read", reason = "fs", allow-invalid = true },' <<<"$pure" || fail "pure std entry without allow-invalid"
grep -q '{ path = "tokio::sync::mpsc::unbounded_channel", reason = "none", allow-invalid = true },' <<<"$pure" \
  || fail "allow-invalid doubled or lost"
[ ! -e "$repo/crates/plain/clippy.toml" ] || fail "stale list of a crate without grant kept"

# when nothing changed, then --check passes
gen --check || fail "--check failed on fresh output"

# when a generated list drifts, then --check fails naming it
sed -i.bak '/std::env::var/d' "$repo/crates/granted/clippy.toml" && rm "$repo/crates/granted/clippy.toml.bak"
if gen --check 2>"$tmp/err"; then fail "--check passed on a drifted list"; fi
grep -q 'crates/granted/clippy.toml differs' "$tmp/err" || fail "drift not named"

# when a crate without a grant has a list, or a granted crate has none, then --check fails
gen
echo "stale" >"$repo/crates/plain/clippy.toml"
if gen --check 2>"$tmp/err"; then fail "--check passed with a stray list"; fi
grep -q 'crates/plain/clippy.toml should not exist' "$tmp/err" || fail "stray list not named"
gen
rm "$repo/crates/pure/clippy.toml"
if gen --check 2>/dev/null; then fail "--check passed with a missing list"; fi

echo ok
