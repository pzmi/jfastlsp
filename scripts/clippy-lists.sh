#!/usr/bin/env bash
# Writes each crate's clippy.toml from the root one (fnd §2.4, ADR 0030): the canonical list minus
# the sections of the grants architecture.toml's [grants] gives the crate, and, for the pure
# crates of [roles], the `#pure ` entries uncommented and `allow-invalid` on the std entries (a
# no_std crate cannot resolve them). A crate with no grant that is not pure
# gets no file: clippy then finds the root one. Clippy has no inheritance, so the root file is
# the only one edited by hand.
#
#   scripts/clippy-lists.sh           write the files
#   scripts/clippy-lists.sh --check   write nothing; exit 1 naming each file that differs
#
# The architecture test's ARCH-clippy-lists (FND-07) checks the same equality independently.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
check=false
case "${1:-}" in
  "") ;;
  --check) check=true ;;
  *) echo "usage: scripts/clippy-lists.sh [--check]" >&2; exit 2 ;;
esac

policy="$root/architecture.toml"
canonical="$root/clippy.toml"
[ -f "$policy" ] || { echo "clippy-lists: $policy missing" >&2; exit 1; }
[ -f "$canonical" ] || { echo "clippy-lists: $canonical missing" >&2; exit 1; }

# toml_list SECTION KEY: the names of a one-line string array under [SECTION] (the policy's own
# layout; the architecture test parses it strictly).
toml_list() {
  awk -v section="[$1]" -v key="$2" '
    /^\[/ { in_section = ($0 == section); next }
    in_section && $1 == key && $2 == "=" {
      line = $0; sub(/^[^=]*=[ \t]*\[/, "", line); sub(/\][ \t]*$/, "", line)
      gsub(/[" \t]/, "", line); n = split(line, names, ",")
      for (i = 1; i <= n; i++) if (names[i] != "") print names[i]
    }' "$policy"
}

# One line per grant: `<grant> <crate> <crate>...` (no associative arrays: macOS ships bash 3.2).
grant_table="$(for grant in process socket fs spawn sleep timer clock env; do
  echo "$grant $(toml_list grants "$grant" | tr '\n' ' ')"
done)"
grants_of() { # grants_of CRATE: its grants, space-separated
  awk -v crate="$1" '{ for (i = 2; i <= NF; i++) if ($i == crate) printf " %s", $1 }' <<<"$grant_table"
}
pure=" $(toml_list roles pure | tr '\n' ' ') "
[ "$pure" != "  " ] || { echo "clippy-lists: [roles] pure is empty" >&2; exit 1; }

# Each member's directory, from the workspace's explicit members list.
members="$(awk '/^members = \[/ { on = 1; next } on && /^\]/ { exit } on { gsub(/[", \t]/, ""); if ($0 != "") print }' "$root/Cargo.toml")"
[ -n "$members" ] || { echo "clippy-lists: no workspace members in Cargo.toml" >&2; exit 1; }

render() { # render "<grants>" <pure:true|false>
  awk -v grants=" $1 " -v pure="$2" '
    BEGIN {
      print "# Generated by `just clippy-lists` from the root clippy.toml (fnd §2.4): the canonical"
      print "# list minus this crate'"'"'s grants in architecture.toml. Do not edit; edit the root file."
      header = 1
    }
    # The root file'"'"'s own header comment stays there.
    header && /^#/ { next }
    header && /^$/ { next }
    { header = 0 }
    /^  # grant: / { name = $3; skip = (index(grants, " " name " ") > 0)
      print (skip ? $0 " (granted to this crate: lifted)" : $0); next }
    /^\]/ { skip = 0 }
    /^  #pure / { if (pure == "true" && !skip) { sub(/^  #pure /, "  "); print }; next }
    # A pure crate is no_std: its std entries cannot resolve there, so they must not warn.
    !skip && pure == "true" && /path = "std::/ && !/allow-invalid/ { sub(/ },$/, ", allow-invalid = true },") }
    !skip { print }
  ' "$canonical"
}

status=0
for dir in $members; do
  crate="$(basename "$dir")"
  grants="$(grants_of "$crate")"
  is_pure=false
  case "$pure" in *" $crate "*) is_pure=true ;; esac
  target="$root/$dir/clippy.toml"
  if [ -z "$grants" ] && [ "$is_pure" = false ]; then
    if [ -e "$target" ]; then
      if $check; then echo "clippy-lists: $dir/clippy.toml should not exist (no grant)" >&2; status=1
      else rm "$target"; fi
    fi
    continue
  fi
  content="$(render "$grants" "$is_pure")"
  if $check; then
    if [ ! -f "$target" ] || [ "$(cat "$target")" != "$content" ]; then
      echo "clippy-lists: $dir/clippy.toml differs from the root list minus its grants; run just clippy-lists" >&2
      status=1
    fi
  else
    printf '%s\n' "$content" >"$target"
  fi
done
exit "$status"
