#!/usr/bin/env bash
# The gitleaks policy of the `secrets` stage (FND-08, fnd §7.4): gitleaks' own default
# configuration, taken from the pinned binary, with its global [allowlist] table removed. That
# table skips whole paths (images, PDFs, fonts, node_modules/, vendor/, go.sum, package-lock.json
# and other lockfiles), so `[extend] useDefault = true` inherited it and a token in such a file
# passed the gate (the FND-05 checkpoint's N5). Every rule, and each rule's own value allowlist
# (placeholders and stopwords, which never match a real token), is kept as gitleaks ships it.
# One global allowlist entry is added back: the path of this policy itself, whose rule texts
# (example key prefixes) trip its own rules once it is committed. It cannot hide a token: the
# stage refuses any .gitleaks.toml that differs from this script's output by a single byte.
#
# Usage: scripts/gitleaks-config.sh [--check] [FILE]     (default FILE: .gitleaks.toml)
#   without --check: write FILE; with --check: exit 1 unless FILE is byte for byte what this
#   script would write from the gitleaks on PATH (so no edit can drop a rule or add an allowlist,
#   and a gitleaks upgrade in mise.toml regenerates it in the same commit).
# Exit: 0 written or equal, 1 different or the default configuration not found, 2 usage.
#
# Pinned by: scripts/test-secrets.sh
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
check=0
file="$root/.gitleaks.toml"
while [ $# -gt 0 ]; do
  case "$1" in
    --check) check=1 ;;
    -h | --help) sed -n '2,/^set -euo/p' "${BASH_SOURCE[0]}" | sed '$d; s/^# \{0,1\}//' >&2; exit 2 ;;
    -*) echo "gitleaks-config: unknown option $1" >&2; exit 2 ;;
    *) file="$1" ;;
  esac
  shift
done

# The real binary, never a mise shim (a shim is a small launcher without the embedded config).
binary=""
if command -v mise >/dev/null 2>&1; then binary="$(cd "$root" && mise which gitleaks 2>/dev/null || true)"; fi
[ -n "$binary" ] || binary="$(command -v gitleaks || true)"
[ -n "$binary" ] && [ -f "$binary" ] || {
  echo "gitleaks is missing: run 'mise install --locked' (or bash scripts/bootstrap-tools.sh)" >&2
  exit 1
}
version="$("$binary" version)"

generated="$(mktemp)"
trap 'rm -f "$generated"' EXIT
{
  printf '# GENERATED by scripts/gitleaks-config.sh from gitleaks %s: its default configuration\n' "$version"
  printf '# without the global [allowlist] (fnd §7.4, FND-08). Do not edit; the secrets stage refuses\n'
  printf '# any other content. A gitleaks upgrade regenerates it: bash scripts/gitleaks-config.sh\n'
  # The default configuration is embedded in the binary as one NUL-terminated text.
  perl -0777 -ne '
    my $start = index($_, "# This file has been auto-generated. Do not edit manually.\n");
    exit 3 if $start < 0;
    my $end = index($_, "\0", $start);
    exit 3 if $end < 0;
    print substr($_, $start, $end - $start);
  ' "$binary" | awk '
    /^\[allowlist\][[:space:]]*$/ || /^\[\[allowlists\]\][[:space:]]*$/ { skip = 1; next }
    skip && /^\[/ { skip = 0 }
    !skip
  '
} >"$generated"

rules="$(grep -c '^\[\[rules\]\]$' "$generated" || true)"
if [ "$rules" -lt 100 ] || grep -qE '^\[(allowlist|\[allowlists)\]' "$generated"; then
  echo "gitleaks-config: the default configuration of $binary was not found whole ($rules rules)" >&2
  exit 1
fi
cat >>"$generated" <<'TOML'

# Added by scripts/gitleaks-config.sh: the one allowlisted path is this policy file, pinned byte
# for byte by the secrets stage.
[[allowlists]]
description = "the generated policy itself"
paths = ['''^\.gitleaks\.toml$''']
TOML

if [ "$check" -eq 0 ]; then
  cp "$generated" "$file"
  exit 0
fi
if ! cmp -s "$generated" "$file"; then
  echo "gitleaks-config: $file is not gitleaks $version's default configuration without its global allowlist; regenerate it with bash scripts/gitleaks-config.sh (fnd §7.4)" >&2
  exit 1
fi
